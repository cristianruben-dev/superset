"""
The format catalog of the report editor: per chart type, the controls the
Visual and Analytics levels of the Format pane draw, and the settings of its
General level. ``format_catalog.json`` is generated by
``superset-frontend/src/auradata/format/formatCatalog.test.ts`` from the control
panels (``UPDATE_FORMAT_CATALOG=1``) and never edited by hand.
"""

from functools import lru_cache
from pathlib import Path
from typing import Any

from superset.utils import json

CATALOG_PATH = Path(__file__).parent / "format_catalog.json"

VISUAL = "visual"
GENERAL = "general"
ANALYTICS = "analytics"
LEVELS = (VISUAL, GENERAL, ANALYTICS)

# Tooltip fields live in the Fields level of the pane but, like small
# multiples, stay in the layout: tools treat them as Analytics.
_LEVEL_OF_SECTION = {"visual": VISUAL, "analytics": ANALYTICS, "fields": ANALYTICS}


@lru_cache(maxsize=1)
def load_catalog() -> dict[str, Any]:
    """The catalog as generated by the frontend."""
    return json.loads(CATALOG_PATH.read_text(encoding="utf-8"))


def chart_types() -> list[str]:
    """The chart types the catalog describes."""
    return sorted(load_catalog()["charts"])


def own_chart_settings() -> frozenset[str]:
    """Chart settings that say something about one chart only."""
    return frozenset(load_catalog()["own_chart_settings"])


def sections_of(viz_type: str, level: str | None = None) -> list[dict[str, Any]]:
    """The sections of a chart type, of one level or all of them (Visual and
    Analytics; the General level is the same for every chart)."""
    chart = load_catalog()["charts"].get(viz_type)
    if chart is None:
        return []
    return [
        {**section, "level": _LEVEL_OF_SECTION[section["level"]]}
        for section in chart["sections"]
        if level is None or _LEVEL_OF_SECTION[section["level"]] == level
    ]


def controls_of(viz_type: str, level: str | None = None) -> dict[str, dict[str, Any]]:
    """The controls of a chart type by key, each with its section and level."""
    return {
        control["key"]: {**control, "section": section["id"], "level": section["level"]}
        for section in sections_of(viz_type, level)
        for control in section["controls"]
    }


def general_spec() -> dict[str, Any]:
    """The settings of the General level, kept in ``meta.auradataFormat``."""
    return load_catalog()["general"]


def general_chart_spec() -> dict[str, Any]:
    """Chart settings of the General level (ECharts tooltip and sampling)."""
    return load_catalog()["general_chart_settings"]
