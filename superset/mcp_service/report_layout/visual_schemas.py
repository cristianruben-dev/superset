"""Schemas of the visual tools: charts made and changed inside a report."""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from superset.mcp_service.chart.schemas import ChartConfig
from superset.mcp_service.report_layout.schemas import (
    _DASHBOARD,
    _OBJECT,
    _OVERLAP,
    _PAGE,
    CellBox,
    DashboardRef,
    ObjectRef,
    PageRef,
)

_FIELD_VALUES = (
    "A column well takes column names (or an ad hoc column "
    '{"sql_expression": ..., "label": ...}); a value well takes saved metric '
    'names, {"name": column, "aggregate": "SUM"|"AVG"|...} or '
    '{"sql_expression": ..., "label": ...}; a plain number column name goes '
    "in as its SUM. A one-field well takes one value, the others a list; null "
    "empties a well."
)


class _Write(BaseModel):
    model_config = ConfigDict(extra="forbid")

    dashboard: DashboardRef = Field(description=_DASHBOARD)


class CreateVisualRequest(_Write):
    page: PageRef | None = Field(None, description=_PAGE + "; the first by default")
    dataset_id: int | str = Field(
        description="Dataset id or uuid: one of the dashboard's workspace or shared"
    )
    config: ChartConfig = Field(
        description="Chart spec, as generate_chart takes it (get_chart_type_schema)"
    )
    chart_name: str | None = Field(
        None, max_length=250, description="Chart title; generated by default"
    )
    x: int | None = Field(None, ge=0, description="Column cell; first free if unset")
    y: int | None = Field(None, ge=0, description="Row cell; first free if unset")
    width: int | None = Field(None, ge=1, description="Width in cells (12 by default)")
    height: int | None = Field(
        None, ge=1, description="Height in cells (12 by default)"
    )
    allow_overlap: bool = Field(False, description=_OVERLAP)


class SetVisualFieldsRequest(_Write):
    object: ObjectRef = Field(description=_OBJECT)
    fields: dict[str, Any] = Field(
        min_length=1,
        description=(
            "Field wells by form data key (get_visual_fields lists them), as the "
            "Fields pane sets them. " + _FIELD_VALUES
        ),
    )


class ChangeVisualDatasetRequest(_Write):
    object: ObjectRef = Field(description=_OBJECT)
    dataset_id: int | str = Field(
        description="New dataset id or uuid: of the dashboard's workspace or shared"
    )
    fields: dict[str, Any] | None = Field(
        None,
        description=(
            "Fields for the wells the new dataset empties, as set_visual_fields "
            "takes them. Without them a change that empties a well is refused."
        ),
    )


class SetVisualSortRequest(_Write):
    object: ObjectRef = Field(description=_OBJECT)
    by: str = Field(
        min_length=1,
        description=(
            "What to sort by: a column or metric label of the chart; for charts "
            "with series also name, sum, min, max or avg; for pivot tables key "
            "(row labels) or value. A refusal lists the choices."
        ),
    )
    ascending: bool = Field(False, description="Ascending; descending by default")


class GetVisualFieldsRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    dashboard: DashboardRef = Field(description=_DASHBOARD)
    object: ObjectRef = Field(description=_OBJECT)


class VisualResponse(BaseModel):
    """What a visual tool made or changed."""

    dashboard_id: int | None = None
    object_id: str | None = Field(None, description="Layout id of the chart object")
    chart_id: int | None = None
    page: str | None = None
    box: CellBox | None = Field(None, description="Where the chart sits, in cells")
    viz_type: str | None = None
    changed: list[str] = Field(
        default_factory=list, description="Form data keys the change wrote"
    )
    fields: dict[str, Any] = Field(
        default_factory=dict, description="The field wells of the chart after it"
    )
    wells: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Each well: name, kind (column or value), whether it takes a list",
    )
    sort: dict[str, Any] | None = Field(None, description="The sort of the chart")
    sort_options: list[str] = Field(default_factory=list)
    dropped: dict[str, Any] = Field(
        default_factory=dict,
        description="Wells and filters the new dataset could not keep",
    )
    moved_from_layout: list[str] = Field(
        default_factory=list,
        description="Settings the layout held over the chart, moved to it",
    )
    warnings: list[str] = Field(default_factory=list)
    error: str | None = None
    error_type: str | None = None
    permission_denied: bool = False
